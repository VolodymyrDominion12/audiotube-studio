"""Spec 009: правила субтитрів у конвеєрі та команда `audiotube subtitles` (без Whisper і YouTube)."""

import contextlib
import io
import shutil
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from audiotube.cli import main
from audiotube.config import Config, load_config
from audiotube.db import Database
from audiotube.pipeline import Pipeline
from audiotube.transcribe import transcribe_audio
from audiotube.transcript import Segment, Transcript

TEXT = "Сьогодні ми розберемо, як працює Docker і навіщо потрібні контейнери у розробці"
OLD_SRT = "1\n00:00:00,000 --> 00:00:20,000\n" + TEXT[:40] + "\n" + TEXT[41:] + "\n"


def cue_durations(srt: str) -> list[float]:
    def sec(stamp: str) -> float:
        h, m, rest = stamp.split(":")
        s, ms = rest.split(",")
        return int(h) * 3600 + int(m) * 60 + int(s) + int(ms) / 1000

    out = []
    for line in srt.splitlines():
        if "-->" in line:
            a, b = (part.strip() for part in line.split("-->"))
            out.append(sec(b) - sec(a))
    return out


class RulesInPipelineTests(unittest.TestCase):
    def test_transcribe_uses_config_rules_and_logs_dense(self):
        """SUB-R10: transcribe пише SRT за правилами з конфігу і повідомляє про «щільні» титри."""
        cfg = Config()
        cfg.transcribe.backend = "openai"
        cfg.transcribe.base_url = "http://localhost:9/v1"
        cfg.transcribe.max_cue_seconds = 3
        fake = Transcript(language="uk", duration=21.0, segments=[
            Segment(0, 20, TEXT),
            Segment(20, 20.5, "Дуже щільний текст на пів секунди"),
        ])
        logs = []
        with tempfile.TemporaryDirectory() as tmp, \
                mock.patch("audiotube.transcribe._run_openai", return_value=fake):
            audio = Path(tmp) / "a.mp3"
            audio.write_bytes(b"fake")
            result = transcribe_audio(audio, Path(tmp) / "work", cfg, log=logs.append)
            durations = cue_durations(result.srt_path.read_text(encoding="utf-8"))
        self.assertGreaterEqual(len(durations), 7)
        self.assertTrue(all(d <= 3.0 + 1e-6 for d in durations), durations)
        self.assertTrue([line for line in logs if "щільн" in line], logs)

    def test_pipeline_autogenerated_srt_uses_rules(self):
        """SUB-R10: SRT, що генерується перед рендером/публікацією, теж за новими правилами."""
        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp, ignore_errors=True)
        (tmp / "config.yaml").write_text("transcribe:\n  max_cue_seconds: 4\n", encoding="utf-8")
        cfg = load_config(root=tmp)
        cfg.ensure_dirs()
        pipe = Pipeline(cfg, log=lambda *_: None)
        self.addCleanup(pipe.db.close)
        audio = cfg.inbox / "ep.mp3"
        audio.write_bytes(b"audio")
        job = pipe.db.add_job(audio, "ep", "Епізод")
        workdir = cfg.workspace / "ep"
        Transcript(language="uk", duration=20, segments=[Segment(0, 20, TEXT)]).save(workdir / "transcript.json")
        srt = pipe._subtitles_path(job, workdir)
        durations = cue_durations(srt.read_text(encoding="utf-8"))
        self.assertTrue(all(d <= 4.0 + 1e-6 for d in durations), durations)


class SubtitlesCommandTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.cfg = load_config(root=self.tmp)
        self.cfg.ensure_dirs()
        self.db = Database(self.cfg.db_path)

    def tearDown(self):
        self.db.close()
        shutil.rmtree(self.tmp, ignore_errors=True)

    def job(self, slug="ep1", transcript=True, **fields):
        audio = self.cfg.inbox / f"{slug}.mp3"
        audio.write_bytes(b"audio")
        job = self.db.add_job(audio, slug, f"Епізод {slug}")
        if transcript:
            Transcript(language="uk", duration=20, segments=[Segment(0, 20, TEXT)]).save(
                self.cfg.workspace / slug / "transcript.json"
            )
        if fields:
            job = self.db.update(job.id, **fields)
        return job

    def srt(self, slug="ep1"):
        return self.cfg.workspace / slug / "subtitles.srt"

    def baks(self, slug="ep1"):
        return sorted((self.cfg.workspace / slug).glob("subtitles.*.srt.bak"))

    def run_cli(self, *args):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = main(["--root", str(self.tmp), "subtitles", *args])
        return code, out.getvalue()

    def dump(self):
        return list(self.db.conn.iterdump())

    def test_creates_missing_srt_idempotently(self):
        """SUB-AC10: SRT створюється з транскрипту; повторний запуск нічого не змінює."""
        job = self.job()
        code, out = self.run_cli()
        self.assertEqual(code, 0, out)
        self.assertTrue(self.srt().exists())
        self.assertGreaterEqual(len(cue_durations(self.srt().read_text(encoding="utf-8"))), 3)
        self.assertEqual(self.db.get(job.id).subtitles, self.srt())
        self.assertIn("створено", out)

        before = self.srt().read_bytes()
        code, out = self.run_cli()
        self.assertEqual(code, 0)
        self.assertEqual(self.srt().read_bytes(), before)
        self.assertIn("--force", out)
        self.assertEqual(self.baks(), [])

    def test_force_rebuilds_with_backup(self):
        """SUB-AC11: --force оновлює старий SRT і кладе .bak; повторний --force — без змін і без .bak."""
        self.job()
        self.srt().write_text(OLD_SRT, encoding="utf-8")
        code, out = self.run_cli("--force")
        self.assertEqual(code, 0, out)
        self.assertNotEqual(self.srt().read_text(encoding="utf-8"), OLD_SRT)
        self.assertEqual(len(self.baks()), 1)
        self.assertEqual(self.baks()[0].read_text(encoding="utf-8"), OLD_SRT)
        self.assertIn("оновлено", out)

        code, out = self.run_cli("--force")
        self.assertEqual(code, 0)
        self.assertEqual(len(self.baks()), 1)
        self.assertIn("без змін", out)

    def test_dry_run_changes_nothing(self):
        """SUB-AC12: --force --dry-run не чіпає файли й БД, показує «було → стане»."""
        self.job()
        self.job("ep2")
        self.srt().write_text(OLD_SRT, encoding="utf-8")
        before = self.dump()
        code, out = self.run_cli("--force", "--dry-run")
        self.assertEqual(code, 0, out)
        self.assertEqual(self.srt().read_text(encoding="utf-8"), OLD_SRT)
        self.assertFalse(self.srt("ep2").exists())
        self.assertEqual(self.baks(), [])
        self.assertEqual(self.dump(), before)
        self.assertRegex(out, r"оновити: титрів 1 → \d+")
        self.assertIn("створити", out)

    def test_published_job_never_touches_youtube(self):
        """SUB-AC13: задача з video_id — SRT оновлено, YouTube не викликано, статус і captions_id ті самі."""
        job = self.job(status="done", video_id="VID1", captions_id="cap1")
        self.srt().write_text(OLD_SRT, encoding="utf-8")
        with mock.patch("audiotube.youtube.build_service") as build, \
                mock.patch("audiotube.youtube.Publisher") as publisher:
            code, out = self.run_cli("--force", str(job.id))
        self.assertEqual(code, 0, out)
        build.assert_not_called()
        publisher.assert_not_called()
        self.assertNotEqual(self.srt().read_text(encoding="utf-8"), OLD_SRT)
        after = self.db.get(job.id)
        self.assertEqual((after.status, after.captions_id, after.video_id), ("done", "cap1", "VID1"))
        self.assertIn("YouTube", out)

    def test_missing_transcript_and_unknown_id(self):
        """SUB-AC14: без транскрипту — пропуск з повідомленням; невідомий id — код 1."""
        job = self.job(transcript=False)
        code, out = self.run_cli(str(job.id), "999")
        self.assertEqual(code, 1)
        self.assertIn("немає транскрипту", out)
        self.assertIn("999", out)
        self.assertIn("не знайдено", out)
        self.assertFalse(self.srt().exists())


if __name__ == "__main__":
    unittest.main()
